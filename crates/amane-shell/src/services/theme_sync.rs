fn write_file(path: &Path, content: &str) {
    if let Some(parent) = path.parent() {
        let _ = fs::create_dir_all(parent);
    }
    let _ = fs::write(path, content);
}

fn spawn_detached(bin: &str, args: &[&str]) {
    let _ = Command::new(bin).args(args).spawn();
}

/// Write theme files for all supported desktop/terminal/TUI apps and trigger non-blocking live reloads.
pub fn sync_all(spec: &PaletteSpec) {
    let Some(home) = std::env::var_os("HOME") else {
        return;
    };
    let h = Path::new(&home);
    let themes_dir = h.join(".config/dotfield/themes");

    write_file(&themes_dir.join("ghostty.conf"), &render_ghostty(spec));
    write_file(&themes_dir.join("kitty.conf"), &render_kitty(spec));
    write_file(&themes_dir.join("foot.ini"), &render_foot(spec));
    write_file(&themes_dir.join("tmux.conf"), &render_tmux(spec));
    write_file(
        &h.join(".config/zellij/themes/dotfield-live.kdl"),
        &render_zellij(spec),
    );
    write_file(
        &h.join(".config/yazi/flavors/dotfield-live.yazi/flavor.toml"),
        &render_yazi(spec),
    );
    write_file(
        &h.join(".config/btop/themes/dotfield-live.theme"),
        &render_btop(spec),
    );
    write_file(
        &h.join(".config/cava/themes/dotfield-live"),
        &render_cava(spec),
    );
    write_file(&themes_dir.join("imv.conf"), &render_imv(spec));
    write_file(&themes_dir.join("mpv.conf"), &render_mpv(spec));
    write_file(&themes_dir.join("nvim.lua"), &render_nvim(spec));
    write_file(&themes_dir.join("zsh.zsh"), &render_zsh(spec));
    write_file(&themes_dir.join("starship.toml"), &render_starship(spec));

    let gtk_css = render_gtk_css(spec);
    write_file(&h.join(".config/gtk-3.0/dotfield-live.css"), &gtk_css);
    write_file(&h.join(".config/gtk-4.0/dotfield-live.css"), &gtk_css);

    write_file(
        &h.join(".config/niri/conf.d/99-amane-theme.kdl"),
        &render_niri_borders(spec),
    );

    // Best-effort non-blocking live reloads
    spawn_detached("pkill", &["-USR1", "kitty"]);
    spawn_detached("pkill", &["-USR1", "cava"]);
    spawn_detached("pkill", &["-USR2", "btop"]);
    spawn_detached("pkill", &["-USR1", "nvim"]);
    spawn_detached(
        "tmux",
        &[
            "source-file",
            &themes_dir.join("tmux.conf").to_string_lossy(),
        ],
    );
    spawn_detached("niri", &["msg", "action", "load-config-file"]);
}

