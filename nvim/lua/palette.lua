-- BLACKSITE Highlight Bridge for Neovim
-- Translates BLACKSITE single source of truth tokens into standard & Treesitter highlight groups
local M = {}

function M.setup()
    -- Reset existing highlights
    vim.cmd("highlight clear")
    if vim.fn.exists("syntax_on") == 1 then
        vim.cmd("syntax reset")
    end
    vim.o.termguicolors = true
    vim.g.colors_name = "blacksite"

    local c = require("palette_generated")
    local hl = function(group, opts)
        vim.api.nvim_set_hl(0, group, opts)
    end

    -- Base editor UI
    hl("Normal", { fg = c.bone, bg = c.void })
    hl("NormalFloat", { fg = c.bone, bg = c.obsidian })
    hl("FloatBorder", { fg = c.iron, bg = c.obsidian })
    hl("FloatTitle", { fg = c.amber, bg = c.obsidian, bold = true })
    hl("ColorColumn", { bg = c.obsidian })
    hl("Cursor", { fg = c.void, bg = c.amber })
    hl("CursorLine", { bg = c.obsidian })
    hl("CursorLineNr", { fg = c.amber, bold = true })
    hl("LineNr", { fg = c.iron })
    hl("SignColumn", { bg = c.void })
    hl("VertSplit", { fg = c.iron })
    hl("WinSeparator", { fg = c.iron })
    hl("StatusLine", { fg = c.bone, bg = c.obsidian })
    hl("StatusLineNC", { fg = c.steel, bg = c.obsidian })
    hl("TabLine", { fg = c.ash, bg = c.obsidian })
    hl("TabLineSel", { fg = c.bone, bg = c.graphite, bold = true })
    hl("TabLineFill", { bg = c.obsidian })
    hl("Visual", { bg = c.graphite })
    hl("VisualNOS", { bg = c.graphite })
    hl("Search", { fg = c.void, bg = c.amber })
    hl("IncSearch", { fg = c.void, bg = c.amber, bold = true })
    hl("CurSearch", { fg = c.void, bg = c.pale_amber, bold = true })
    hl("Pmenu", { fg = c.ash, bg = c.obsidian })
    hl("PmenuSel", { fg = c.bone, bg = c.graphite, bold = true })
    hl("PmenuSbar", { bg = c.obsidian })
    hl("PmenuThumb", { bg = c.iron })

    -- Standard Syntax highlights
    hl("Comment", { fg = c.steel, italic = true })
    hl("Constant", { fg = c.amber })
    hl("String", { fg = c.success })
    hl("Character", { fg = c.success })
    hl("Number", { fg = c.amber })
    hl("Boolean", { fg = c.amber, bold = true })
    hl("Float", { fg = c.amber })
    hl("Identifier", { fg = c.bone })
    hl("Function", { fg = c.pale_amber })
    hl("Statement", { fg = c.amber, bold = true })
    hl("Conditional", { fg = c.amber, bold = true })
    hl("Repeat", { fg = c.amber, bold = true })
    hl("Label", { fg = c.amber })
    hl("Operator", { fg = c.ash })
    hl("Keyword", { fg = c.amber, bold = true })
    hl("Exception", { fg = c.crimson, bold = true })
    hl("PreProc", { fg = c.steel })
    hl("Include", { fg = c.amber })
    hl("Define", { fg = c.amber })
    hl("Macro", { fg = c.pale_amber })
    hl("Type", { fg = c.pale_amber })
    hl("StorageClass", { fg = c.amber })
    hl("Structure", { fg = c.amber })
    hl("TypeDef", { fg = c.pale_amber })
    hl("Special", { fg = c.pale_amber })
    hl("SpecialChar", { fg = c.success })
    hl("Tag", { fg = c.amber })
    hl("Delimiter", { fg = c.ash })
    hl("Underlined", { underline = true })
    hl("Bold", { bold = true })
    hl("Italic", { italic = true })
    hl("Error", { fg = c.crimson, bold = true })
    hl("Todo", { fg = c.void, bg = c.amber, bold = true })

    -- Treesitter groups
    hl("@comment", { link = "Comment" })
    hl("@string", { link = "String" })
    hl("@string.escape", { fg = c.pale_amber })
    hl("@string.regex", { fg = c.pale_amber })
    hl("@character", { link = "Character" })
    hl("@number", { link = "Number" })
    hl("@boolean", { link = "Boolean" })
    hl("@float", { link = "Float" })
    hl("@function", { link = "Function" })
    hl("@function.builtin", { fg = c.pale_amber, bold = true })
    hl("@function.call", { link = "Function" })
    hl("@function.macro", { fg = c.pale_amber })
    hl("@method", { link = "Function" })
    hl("@method.call", { link = "Function" })
    hl("@constructor", { fg = c.pale_amber })
    hl("@parameter", { fg = c.bone })
    hl("@keyword", { link = "Keyword" })
    hl("@keyword.function", { link = "Keyword" })
    hl("@keyword.operator", { fg = c.ash })
    hl("@keyword.return", { fg = c.amber, bold = true })
    hl("@conditional", { link = "Conditional" })
    hl("@repeat", { link = "Repeat" })
    hl("@label", { link = "Label" })
    hl("@operator", { link = "Operator" })
    hl("@exception", { link = "Exception" })
    hl("@type", { link = "Type" })
    hl("@type.builtin", { fg = c.pale_amber, bold = true })
    hl("@type.definition", { link = "TypeDef" })
    hl("@structure", { link = "Structure" })
    hl("@variable", { fg = c.bone })
    hl("@variable.builtin", { fg = c.amber })
    hl("@constant", { link = "Constant" })
    hl("@constant.builtin", { fg = c.amber, bold = true })
    hl("@constant.macro", { link = "Constant" })
    hl("@property", { fg = c.bone })
    hl("@field", { fg = c.bone })
    hl("@punctuation.delimiter", { fg = c.ash })
    hl("@punctuation.bracket", { fg = c.ash })
    hl("@punctuation.special", { fg = c.amber })

    -- Diagnostics
    hl("DiagnosticError", { fg = c.crimson })
    hl("DiagnosticWarn", { fg = c.amber })
    hl("DiagnosticInfo", { fg = c.steel })
    hl("DiagnosticHint", { fg = c.ash })
    hl("DiagnosticUnderlineError", { undercurl = true, sp = c.crimson })
    hl("DiagnosticUnderlineWarn", { undercurl = true, sp = c.amber })
    hl("DiagnosticUnderlineInfo", { undercurl = true, sp = c.steel })
    hl("DiagnosticUnderlineHint", { undercurl = true, sp = c.ash })

    -- Diff & Git
    hl("DiffAdd", { fg = c.success, bg = c.obsidian })
    hl("DiffChange", { fg = c.amber, bg = c.obsidian })
    hl("DiffDelete", { fg = c.crimson, bg = c.obsidian })
    hl("DiffText", { fg = c.void, bg = c.amber })
end

function M.reload()
    package.loaded["palette_generated"] = nil
    package.loaded["palette"] = nil
    require("palette").setup()
    vim.notify("BLACKSITE palette reloaded", vim.log.levels.INFO)
end

return M
